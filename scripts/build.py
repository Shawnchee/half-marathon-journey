#!/usr/bin/env python3
"""Validate the public-data allowlist and refresh browser + README data. No dependencies."""
import hashlib
import datetime as dt
import json
import math
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def require(condition,message):
    if not condition: raise ValueError(message)
def keys(value,allowed):
    require(isinstance(value,dict) and set(value)==set(allowed),'Unexpected or missing data fields; only the documented public schema is allowed.')
def date(s):
    require(isinstance(s,str) and re.fullmatch(r'\d{4}-\d{2}-\d{2}',s) is not None,'Use YYYY-MM-DD dates.')
    return dt.date.fromisoformat(s)
def number(x): return type(x) in (float,int) and math.isfinite(x)
def pace(s): return f'{s//60}:{s%60:02}'
def build():
    j=json.loads((ROOT/'data/journey.json').read_text())
    logs=json.loads((ROOT/'data/logs.json').read_text())
    weeks=json.loads((ROOT/'data/weeks.json').read_text())
    community=json.loads((ROOT/'data/community.json').read_text())
    keys(community,['enabled','repo','repoId','category','categoryId'])
    require(type(community['enabled']) is bool,'Community enabled must be true or false.')
    for field in ['repo','repoId','category','categoryId']:
        require(isinstance(community[field],str) and len(community[field])<=200,'Invalid discussion setting.')
    if community['enabled']:
        require(re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+',community['repo']) is not None,'Enter the public owner/repository for Discussions.')
        require(all(community[field].strip() for field in ['repoId','category','categoryId']),'Complete the giscus repository and category settings before enabling notes.')
    keys(j,['title','startDate','raceDate','raceDistanceKm','targetPaceSecondsPerKm','targetQualifier','historicalBests'])
    require(j['title']=='The road to 21.1' and j['startDate']=='2026-10-22' and j['raceDate']=='2026-12-13','Journey identity and dates must match this project.')
    require(j['raceDistanceKm']==21.0975 and j['targetPaceSecondsPerKm']==360 and j['targetQualifier']=='strictly-under','Keep the supplied half-marathon goal unchanged.')
    require(j['historicalBests']==[{'distanceKm':5,'paceSecondsPerKm':292,'when':'Last year'},{'distanceKm':10,'paceSecondsPerKm':363,'when':'Last year','longestReported':True}],'Historical bests must match the supplied facts.')
    require(isinstance(logs,list),'Logs must be an array.')
    for r in logs:
        keys(r,['date','distanceKm','durationSeconds','effort'])
        require(date(r['date'])>=date(j['startDate']),'Log date must be on or after the journey start; records can continue after race day.')
        require(date(r['date'])<=dt.date.today(),'Do not record future training as complete.')
        require(number(r['distanceKm']) and r['distanceKm']>0,'Distance must be a positive number.')
        require(type(r['durationSeconds']) is int and r['durationSeconds']>0,'Duration must be positive whole seconds.')
        require(number(r['effort']) and 1<=r['effort']<=10,'Effort must be from 1 to 10.')
    require(isinstance(weeks,list) and len(weeks)==8,'Keep eight flexible training windows.')
    previous=date(j['startDate'])-dt.timedelta(days=1)
    for w in weeks:
        keys(w,['startDate','endDate','title','target','adjustment','sessions'])
        require(date(w['startDate'])==previous+dt.timedelta(days=1),'Weekly windows must be contiguous.')
        require(date(w['endDate'])>=date(w['startDate']),'Invalid week window.')
        for field in ['title','target','adjustment']:
            require(isinstance(w[field],str) and 0<len(w[field])<=300,'Use short, anonymous plan text.')
        require(isinstance(w['sessions'],list) and len(w['sessions'])==3,'Each week needs three flexible session slots.')
        for session in w['sessions']:
            keys(session,['kind','minKm','maxKm','optional','paceMinSecondsPerKm','paceMaxSecondsPerKm'])
            require(session['kind'] in ['Easy 1','Easy 2','Long easy','Race'],'Invalid session label.')
            require(type(session['optional']) is bool,'Optional-session status must be true or false.')
            lo,hi=session['paceMinSecondsPerKm'],session['paceMaxSecondsPerKm']
            require((lo is None and hi is None and session['maxKm']==0) or (type(lo) is int and type(hi) is int and 180<=lo<=hi<=900),'Use valid pace guides in seconds per kilometre, or null for rest.')
            require(number(session['minKm']) and number(session['maxKm']) and 0<=session['minKm']<=session['maxKm']<=21.0975,'Invalid planned distance range.')
        previous=date(w['endDate'])
    require(previous==date(j['raceDate']),'Weekly windows must end on race day.')
    payload=json.dumps({'journey':j,'logs':logs,'weeks':weeks,'community':community},ensure_ascii=True).replace('<','\\u003c').replace('>','\\u003e').replace('&','\\u0026')
    (ROOT/'assets/data.js').write_text('// Generated by scripts/build.py. Edit data/*.json, then rebuild.\nwindow.JOURNAL = '+payload+';\n')
    total=sum(r['distanceKm'] for r in logs)
    rows=['| Date | Distance | Pace | Duration | Effort |','| :--- | ---: | ---: | ---: | ---: |']
    for r in sorted(logs,key=lambda r:r['date']):
        p=math.floor(r['durationSeconds']/r['distanceKm']+.5)
        rows.append(f"| {r['date']} | {r['distanceKm']:.1f} km | {pace(p)} min/km | {pace(r['durationSeconds'])} | {r['effort']}/10 |")
    latest=max((r['date'] for r in logs),default='No entries')
    summary=f'**{total:.1f} km logged · {len(logs)} completed run'+('s' if len(logs)!=1 else '')+f' · Last entry: {latest}**\n\n'+'\n'.join(rows)
    for path in [ROOT/'README.md', ROOT/'docs/GUIDE.md']:
        if path.exists():
            content=path.read_text()
            content=re.sub(r'<!-- STATS:START -->.*?<!-- STATS:END -->','<!-- STATS:START -->\n'+summary+'\n<!-- STATS:END -->',content,flags=re.S)
            path.write_text(content)
    # Content fingerprints prevent stale charts/styles after a Pages deployment.
    html_path=ROOT/'index.html'
    def fingerprint(match):
        asset=match.group(2)
        digest=hashlib.sha256((ROOT/asset).read_bytes()).hexdigest()[:12]
        return match.group(1)+asset+'?v='+digest+match.group(3)
    html_path.write_text(re.sub(r'((?:src|href)=")(assets/[^"?]+\.(?:css|js))(?:\?v=[^"]*)?(")',fingerprint,html_path.read_text()))
    print('Validated public data; refreshed browser data, guide statistics, and asset fingerprints.')
if __name__=='__main__': build()
